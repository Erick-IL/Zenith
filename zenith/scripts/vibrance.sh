#!/usr/bin/env bash
# Digital vibrance, similar to the NVIDIA panel on Windows.
#
#   vibrance.sh set <0..100> - set and apply
#   vibrance.sh get - current value
#   vibrance.sh restore - apply saved (for autorun)
#
# On Wayland there is no handle from nvidia-settings: it worked through XRandR and on
# Wayland session does not work at all. But it controls the color of the entire screen
# the compositor itself - Hyprland can run a frame through its shader, and
# Saturation is considered in the same place where the picture is collected. Method does not depend
# from video card: works equally on NVIDIA, AMD and Intel.
#
# The scale deliberately repeats the usual: 50 - as is, 100 - maximum,
# below 50 - muting to black and white at zero.
set -u

CONF="${XDG_CONFIG_HOME:-$HOME/.config}"
SHADER_DIR="$CONF/hypr/shaders"
SHADER="$SHADER_DIR/vibrance.frag"
STATE="$CONF/zenith/.vibrance"

cur() { [ -f "$STATE" ] && cat "$STATE" || echo 50; }

# Tell Hyprland which shader to take.
#
# Through hyprctl eval, not keyword: new (non-legacy, aka Lua) parser
# keyword config silently rejects - and exits with a zero code, so
# that the error is not visible, and the setting does not go anywhere. Exactly the same thing already
# happened with the monitor settings. keyword is left as a fallback for
# old configs.
set_shader() {
    local val="$1" out
    out="$(hyprctl eval "hl.config({ decoration = { screen_shader = \"$val\" } })" 2>&1)"
    case "$out" in
        ok*) return 0 ;;
        *)   hyprctl keyword decoration:screen_shader "$val" >/dev/null 2>&1 ;;
    esac
}


# What GLSL dialect the linker asks for is not a guess, but what is hardcoded into it
# himself. Hyprland links our fragment shader with its vertex shader, and versions
# must match: on "#version 300 es" inside Hyprland shader without line
# version is considered 1.00, and the NVIDIA driver responds “all shaders must use the same
# shading language version", drawing a red frame over the screen. Mesa the same
# discrepancies are forgiven silently - so it’s impossible to check this on one machine.
#
# We ask the binary: grep -a reads it as text, binutils is not needed.
dialect() {
    local bin ver
    bin=$(command -v Hyprland 2>/dev/null) || { echo es3; return; }
    ver=$(grep -ao '#version [0-9]\+ es' "$bin" 2>/dev/null | head -1 | tr -dc '0-9')
    [ -n "$ver" ] && [ "$ver" -ge 300 ] && echo es3 || echo es1
}

# ASCII only: NVIDIA compiler stumbles on non-ASCII bytes even internally
# comments and answers “error C3001: no program defined”, that is, as if
# There is no source at all. Therefore, explanations in Russian remain here, but in .frag
# English is leaving.
#
# lum - brightness according to Rec.709, gray of the same lightness as the color: from it
#        we push off so that the rise in saturation does not drive into overexposure.
# sat - how saturated the color is now. This is the difference between “vibrance” and
#        simple saturation: we touch bright colors lightly, faded ones -
#        strongly, otherwise faces and the sky are the first to go into acid.
#
# We write to a temporary file and rename it. The linker rereads the shader,
# as soon as the path is called to him, and the slider calls us to every movement - and
# Hyprland managed to open the file halfway through the recording. Renaming within
# file system atomically: it sees either the entire old file or the new one.
write_shader() {   # $1 - strength, $2 - es3 | es1
    local strength="$1" want="$2" tmp="$SHADER.new"
    local head body_out sample

    if [ "$want" = "es3" ]; then
        head="#version 300 es
precision highp float;
in vec2 v_texcoord;
uniform sampler2D tex;
out vec4 fragColor;"
        sample="texture(tex, v_texcoord)"
        body_out="fragColor"
    else
        head="precision highp float;
varying vec2 v_texcoord;
uniform sampler2D tex;"
        sample="texture2D(tex, v_texcoord)"
        body_out="gl_FragColor"
    fi

    cat > "$tmp" <<EOF
// Generated by zenith/scripts/vibrance.sh -- edits will be overwritten.
$head

const float STRENGTH = ${strength};

void main() {
    vec4 px = $sample;

    float lum = dot(px.rgb, vec3(0.2126, 0.7152, 0.0722));

    float mx  = max(px.r, max(px.g, px.b));
    float mn  = min(px.r, min(px.g, px.b));
    float sat = mx - mn;

    float weight = STRENGTH > 0.0 ? (1.0 - sat) : 1.0;
    float amount = STRENGTH * weight;
    vec3 outRgb = mix(vec3(lum), px.rgb, 1.0 + amount);

    $body_out = vec4(clamp(outRgb, 0.0, 1.0), px.a);
}
EOF
    mv -f "$tmp" "$SHADER"
}

apply() {
    local pct="$1"

    # 50 - neutral: remove the shader completely so that the frame goes past the excess
    # passage. So "off" really doesn't cost anything.
    if [ "$pct" -eq 50 ]; then
        set_shader '[[EMPTY]]'
        return
    fi

    # 50→0.0, 100→1.0, 0→-1.0
    local strength
    strength="$(awk -v p="$pct" 'BEGIN { printf "%.4f", (p - 50) / 50 }')"

    mkdir -p "$SHADER_DIR"
    write_shader "$strength" "$(dialect)"
    set_shader "$SHADER"

}


case "${1:-}" in
    set)
        pct="${2:-50}"
        [ "$pct" -lt 0 ]   && pct=0
        [ "$pct" -gt 100 ] && pct=100
        mkdir -p "$(dirname "$STATE")"
        echo "$pct" > "$STATE"
        apply "$pct"
        echo "$pct"
        ;;
    get)     cur ;;
    restore) apply "$(cur)" ;;
    *)       echo "usage: vibrance.sh set <0..100>|get|restore" >&2; exit 1 ;;
esac
